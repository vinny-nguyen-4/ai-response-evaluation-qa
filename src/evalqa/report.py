"""Excel dashboard workbook (openpyxl)."""

from __future__ import annotations

from pathlib import Path

import pandas as pd
from openpyxl import Workbook
from openpyxl.drawing.image import Image as XLImage
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

HEADER_FILL = PatternFill("solid", fgColor="1F3A5F")
HEADER_FONT = Font(bold=True, color="FFFFFF")
TITLE_FONT = Font(bold=True, size=14)
THIN = Border(bottom=Side(style="thin", color="D9D9D9"))

PCT_COLS = ("rate", "share", "agreement", "accuracy", "caught_", "ci_")
USD_COLS = ()


def _fmt_for(col: str) -> str | None:
    c = col.lower()
    if c in ("krippendorff_alpha", "mae_vs_gold", "bias"):
        return "0.000"
    if c == "nps":
        return "0.0"
    if any(k in c for k in PCT_COLS):
        return "0.00%"
    return None


def write_table(ws, df: pd.DataFrame, start_row: int = 3, title: str | None = None, note: str | None = None) -> int:
    if title:
        ws.cell(row=1, column=1, value=title).font = TITLE_FONT
    if note:
        ws.cell(row=2, column=1, value=note).font = Font(italic=True, color="595959")
    for j, col in enumerate(df.columns, start=1):
        c = ws.cell(row=start_row, column=j, value=str(col))
        c.fill, c.font = HEADER_FILL, HEADER_FONT
        c.alignment = Alignment(horizontal="center", wrap_text=True)
    for i, row in enumerate(df.itertuples(index=False), start=start_row + 1):
        for j, val in enumerate(row, start=1):
            if isinstance(val, pd.Timestamp):
                val = val.to_pydatetime()
            cell = ws.cell(row=i, column=j, value=val)
            cell.border = THIN
            fmt = _fmt_for(df.columns[j - 1])
            if fmt and isinstance(val, (int, float)):
                cell.number_format = fmt
            elif hasattr(val, "year"):
                cell.number_format = "mmm yyyy"
    for j, col in enumerate(df.columns, start=1):
        width = max(len(str(col)), *(len(f"{v:,.2f}") if isinstance(v, float) else len(str(v)) for v in df.iloc[:, j - 1])) \
            if len(df) else len(str(col))
        ws.column_dimensions[get_column_letter(j)].width = min(max(width + 2, 10), 38)
    ws.freeze_panes = ws.cell(row=start_row + 1, column=1)
    return start_row + len(df) + 1


def build_workbook(path: Path, sheets: dict[str, tuple[pd.DataFrame, str]], kpis: list[tuple[str, str]],
                   images: list[Path]) -> Path:
    wb = Workbook()
    dash = wb.active
    dash.title = "Dashboard"
    dash["A1"] = "AI Response Evaluation – Quality Dashboard"
    dash["A1"].font = Font(bold=True, size=16)
    dash["A2"] = "Synthetic data. All figures generated by the pipeline in this repository."
    dash["A2"].font = Font(italic=True, color="595959")
    for i, (label, value) in enumerate(kpis, start=4):
        dash.cell(row=i, column=1, value=label).font = Font(bold=True)
        dash.cell(row=i, column=2, value=value).alignment = Alignment(horizontal="right")
    dash.column_dimensions["A"].width = 46
    dash.column_dimensions["B"].width = 18
    anchor_row = 4
    for k, img_path in enumerate(images):
        img = XLImage(str(img_path))
        img.width, img.height = img.width * 0.42, img.height * 0.42
        col = "D" if k % 2 == 0 else "N"
        dash.add_image(img, f"{col}{anchor_row}")
        if k % 2 == 1:
            anchor_row += 25
    for name, (df, note) in sheets.items():
        ws = wb.create_sheet(name[:31])
        write_table(ws, df, title=name, note=note)
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


